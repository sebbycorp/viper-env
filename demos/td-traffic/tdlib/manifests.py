def client_cel() -> str:
    ua = 'request.headers["user-agent"]'
    parts = []
    for label, conds in CLIENT_RULES:
        test = " || ".join(f'{ua}.{op}("{s}")' for op, s in conds)
        parts.append(f'{"(" + test + ")" if len(conds) > 1 else test} ? "{label}" : ')
    return "".join(parts) + f'"{CLIENT_OTHER}"'


