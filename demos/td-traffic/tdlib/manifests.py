def _key_entry(org: Org, k) -> str:
    md = {"id": k.id, "organization": org.name, "group": k.group, "user": service_identity(k),
          "custom": {"team": k.team, "project": k.project}}
    return json.dumps({"key": k.secret, "keyHash": None, "metadata": md}, separators=(",", ":"))


