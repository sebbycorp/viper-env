#!/usr/bin/env python3
"""Regenerate apps/agentgateway-system/model-costs.yaml from https://models.dev/api.json.

models.dev and the agentgateway catalog both price in USD per 1M tokens; the catalog
wants exact decimal strings. Usage: python3 scripts/gen-model-costs.py [providers...]
"""
import json, sys, urllib.request
from datetime import date
from decimal import Decimal

PROVIDERS = sys.argv[1:] or ["openai"]
OUT = "apps/agentgateway-system/model-costs.yaml"
FIELDS = {"input": "input", "output": "output", "cache_read": "cacheRead",
          "cache_write": "cacheWrite", "reasoning": "reasoning",
          "input_audio": "inputAudio", "output_audio": "outputAudio"}

def dec(v):
    return format(Decimal(str(v)).normalize(), "f")


def rates(cost):
    return {FIELDS[k]: dec(v) for k, v in cost.items() if k in FIELDS and v is not None}


req = urllib.request.Request("https://models.dev/api.json", headers={"User-Agent": "viper-env"})
src = json.load(urllib.request.urlopen(req, timeout=60))
catalog = {"providers": {}}
for p in PROVIDERS:
    models = {}
    for mid, m in sorted(src[p]["models"].items()):
        cost = m.get("cost")
        if not cost or not rates(cost):
            continue
        entry = {"rates": rates(cost)}
        tiers = [{"contextOver": t["tier"]["size"], "rates": rates(t)}
                 for t in cost.get("tiers", []) if t.get("tier", {}).get("type") == "context"]
        if tiers:
            entry["tiers"] = tiers
        entry["tags"] = ["models.dev"]
        models[mid] = entry
    catalog["providers"][p] = {"models": models}

body = json.dumps(catalog, indent=2)
with open(OUT, "w") as f:
    f.write(f"""# LLM cost catalog (USD per 1M tokens, as strings) for agentgateway llm.cost / Cost Management.
# Generated by scripts/gen-model-costs.py from https://models.dev/api.json on {date.today()}.
# Providers: {', '.join(PROVIDERS)}. Do not hand-edit; re-run the script to refresh prices.
# Self-hosted models (DGX Spark) are priced separately in spark-costs.yaml.
apiVersion: v1
kind: ConfigMap
metadata:
  name: model-costs
  namespace: agentgateway-system
data:
  catalog.json: |
""")
    f.write("".join("    " + line + "\n" for line in body.splitlines()))
print(f"wrote {OUT}: " + ", ".join(f"{p}={len(catalog['providers'][p]['models'])} models" for p in PROVIDERS))
